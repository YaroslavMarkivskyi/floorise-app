export async function seedUserDefaults(userId: string): Promise<void> {
  for (const slotDef of SLOTS) {
    const slot = await db.mealSlot.create({
      data: {
        userId,
        order: slotDef.order,
        name: slotDef.name,
        time: slotDef.time,
        targetKcal: slotDef.targetKcal,
      },
    })

    const dishDefs = SLOT_DISHES[slotDef.order]
    for (let i = 0; i < dishDefs.length; i++) {
      const d = dishDefs[i]
      const dish = await db.dish.create({
        data: {
          userId,
          name: d.name,
          kcal: d.kcal,
          cookTime: d.cookTime,
          source: "seed",
          ingredients: d.ingredients,
          steps: d.steps,
        },
      })
      await db.slotDish.create({
        data: { slotId: slot.id, dishId: dish.id, position: i },
      })
    }
  }
}
